#!/usr/bin/env python3
"""Render the scope baseline and NEW-issue payloads without contacting GitHub.

GitHub is authoritative for live execution state. These payloads initialize only
new resources. They are never patch instructions for existing issues or fields.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from typing import Any

SOURCES = {
    "backlog": "planning/project-backlog.json",
    "coverage": "planning/coverage-matrix.json",
    "decisions": "planning/decision-register.json",
    "releases": "planning/release-manifest.json",
}
REPOSITORY = "Pick-Your-AI/pick-your-ai-catalog-pipeline"
MARKER_PREFIX = "pick-your-ai-catalog-pipeline:"
GENERATED = "<!-- Generated by scripts/render_docs.py; edit the planning JSON sources. -->"
NATIVE_ID = re.compile(r"CP(?:-\d{2}(?:\.\d{2})?)?\Z")
PROJECT_FIELDS = {
    "Status": "status",
    "Priority": "priority",
    "Workstream": "workstream",
    "Record Type": "level",
    "Readiness": "readiness",
    "Evidence Confidence": "evidence_confidence",
    "Source Rights Status": "source_rights_status",
    "Dependency Status": "dependency_status",
    "Effort": "effort",
    "Release Phase": "phase",
    "Acceptance Status": "acceptance_status",
}


class RenderError(ValueError):
    """Invalid or ambiguous source cannot be published as a planning artifact."""


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise RenderError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def _reject_constant(value: str) -> None:
    raise RenderError(f"non-finite JSON number: {value}")


def load_sources(root: Path) -> tuple[dict[str, Any], dict[str, str]]:
    bundle: dict[str, Any] = {}
    digests: dict[str, str] = {}
    for key, relative in SOURCES.items():
        raw = (root / relative).read_bytes()
        bundle[key] = json.loads(
            raw.decode("utf-8"),
            object_pairs_hook=_unique_object,
            parse_constant=_reject_constant,
        )
        digests[relative] = hashlib.sha256(raw).hexdigest()
    return bundle, digests


def native_records(backlog: dict[str, Any]) -> list[dict[str, Any]]:
    records = [backlog["program"]]
    for epic in backlog["epics"]:
        records.append(epic)
        records.extend(epic["work_packages"])
    seen: set[str] = set()
    for record in records:
        identifier = record["id"]
        if not isinstance(identifier, str) or not NATIVE_ID.fullmatch(identifier):
            raise RenderError(f"unsafe or unsupported native record ID: {identifier!r}")
        if identifier in seen:
            raise RenderError(f"duplicate native record ID: {identifier}")
        seen.add(identifier)
        for key in PROJECT_FIELDS.values():
            if key not in record:
                raise RenderError(f"{identifier}: missing Project field source {key}")
    for record in records:
        parent = record.get("parent")
        if parent is not None and parent not in seen:
            raise RenderError(f"{record['id']}: missing native parent {parent}")
        for dependency in record.get("blocked_by", []):
            if dependency not in seen:
                raise RenderError(f"{record['id']}: missing native dependency {dependency}")
    return records


def cell(value: Any) -> str:
    """Escape values placed in a Markdown table without losing source text."""
    return str(value).replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def bullet_list(values: list[str]) -> list[str]:
    return [f"- {value}" for value in values] or ["- None specified."]


def native_link(identifier: str, prefix: str = "../planning/issues/") -> str:
    return f"[{identifier}]({prefix}{identifier}.md)"


def marker(identifier: str) -> str:
    return f"<!-- {MARKER_PREFIX}{identifier} -->"


def issue_body(record: dict[str, Any], records: list[dict[str, Any]]) -> str:
    identifier = record["id"]
    parent = record.get("parent")
    children = [candidate for candidate in records if candidate.get("parent") == identifier]
    lines = [marker(identifier), "", "## Objective", "", record["outcome"], "", "## Planning identity", ""]
    lines.extend([
        "| Field | Prepared baseline value |",
        "| --- | --- |",
        f"| Stable ID | `{identifier}` |",
        *[f"| {name} | {cell(record[key])} |" for name, key in PROJECT_FIELDS.items()],
        "| Actual ownership | Native GitHub Assignees; unassigned until accepted |",
        "",
        "These values initialize a new issue only. GitHub owns live status, Assignees, review decisions and checklist progress; reconciliation must preserve them.",
        "",
        "## Native relationships",
        "",
    ])
    if parent:
        lines.append(f"Intended native parent: `{parent}`. Resolve this stable ID to a verified issue identity before creating the relationship.")
    else:
        lines.append("This is the target repository's program root. It has no internal native parent.")
    if record.get("parent_research_issue"):
        lines.extend(["", f"Canonical parent research handoff: {record['parent_research_issue']}. Reconcile any proposed cross-repository native parent against live ancestry; do not force reparent or close the broader research issue."])
    if children:
        lines.extend(["", "The following independently reviewable children require native sub-issue relationships. This table is a scope index, not a second child-completion checklist.", "", "| Child stable ID | Deliverable |", "| --- | --- |"])
        lines.extend(f"| `{child['id']}` | {cell(child['title'])} |" for child in children)
    dependencies = record.get("blocked_by", [])
    lines.extend(["", "## Required prerequisites", ""])
    if dependencies:
        index = {candidate["id"]: candidate for candidate in records}
        for dependency in dependencies:
            prerequisite = index[dependency]
            lines.append(f"- `{dependency}` — {prerequisite['outcome']}")
        lines.extend(["", "These are intended native blocked-by prerequisites. Resolve stable IDs after publication and verify actual accepted outcomes before Ready."])
    else:
        lines.append("No additional native blocked-by edge is declared. Parent acceptance still requires its child outcomes, and ownership/decision gates remain applicable.")
    if record.get("readiness_reasons"):
        lines.extend(["", "Current planning constraints:", "", *bullet_list(record["readiness_reasons"])])
    if record.get("tasks"):
        lines.extend(["", "## Tasks and subtasks", "", "Checklist IDs remain stable. Promote a task to its own native issue only for an independently accepted owner or review boundary, preserving its identity and progress.", ""])
        for task in record["tasks"]:
            lines.append(f"- [{'x' if task['done'] else ' '}] `{task['id']}` — {task['title']}")
            for subtask in task.get("subtasks", []):
                lines.append(f"  - [{'x' if subtask['done'] else ' '}] `{subtask['id']}` — {subtask['title']}")
    for heading, key in [
        ("Acceptance criteria", "acceptance_criteria"),
        ("Required outputs", "outputs"),
        ("Verification and completion evidence", "completion_evidence"),
        ("Definition of done", "definition_of_done"),
        ("Scope exclusions", "scope_exclusions"),
        ("Risks", "risks"),
    ]:
        if record.get(key):
            lines.extend(["", f"## {heading}", "", *bullet_list(record[key])])
    handoffs = list(dict.fromkeys(record.get("external_handoffs", [])))
    if handoffs:
        lines.extend(["", "## Canonical authority and receiving handoffs", "", "These are references and receiving boundaries, not automatically unresolved native blockers. Completed research stays completed; new source or semantic decisions use its established process.", "", *bullet_list(handoffs)])
    lines.extend([
        "",
        "## Completion boundary",
        "",
        "Repository setup, issue creation, local synthetic tests and a merged partial implementation do not satisfy future production acceptance. Retain exact source, artifact, review and consumer receipts. Do not reopen completed research, mutate frozen builder v1, grant unknown source rights, or infer an independent review from the author's own checks.",
        "",
        "All bootstrap examples are synthetic. This issue grants no paid subscription, live retrieval contrary to source policy, production deployment, or operating-role acceptance. Use Refs for partial work and keep the issue open until its literal criteria and required receiving handoffs are accepted.",
    ])
    return "\n".join(lines) + "\n"


def make_payload(bundle: dict[str, Any], digests: dict[str, str], records: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "schema_version": "catalog-pipeline-github-payloads-1",
        "repository": REPOSITORY,
        "mode": "prepared-only",
        "mutation_policy": "create_missing_preserve_live",
        "reset_existing_progress": False,
        "external_parent_url": bundle["backlog"]["program"]["parent_research_issue"],
        "source_sha256": digests,
        "items": [
            {
                "id": record["id"],
                "title": f"[{record['id']}] {record['title']}",
                "body": issue_body(record, records),
                "labels": [],
                "assignees": [],
                "issue_type": "Feature" if record["level"] in ("Program", "Epic") else "Task",
                "parent_id": record.get("parent"),
                "blocked_by": record.get("blocked_by", []),
                "project_fields": {name: record[key] for name, key in PROJECT_FIELDS.items()},
            }
            for record in records
        ],
    }


def render_delivery(bundle: dict[str, Any], records: list[dict[str, Any]]) -> str:
    backlog, coverage, decisions, releases = (bundle[key] for key in ("backlog", "coverage", "decisions", "releases"))
    packages = [record for record in records if record["level"] == "Work Package"]
    tasks = [task for package in packages for task in package["tasks"]]
    subtasks = [subtask for task in tasks for subtask in task["subtasks"]]
    lines = [GENERATED, "", "# Catalog pipeline delivery plan", "", backlog["program"]["outcome"], "", "## Preparation and execution boundary", "", backlog["state"], "", f"The baseline contains **{len(records)} intended native issues**: one Program, {len(backlog['epics'])} Epics and {len(packages)} independently reviewable Work Packages. Their implementation detail is {len(tasks)} stable checklist Tasks and {len(subtasks)} Subtasks.", "", backlog["hierarchy_policy"], "", backlog["ownership_policy"], "", backlog["reconciliation_policy"], "", "The [generated issue payloads](../planning/github-issue-payloads.json) and [individual issue bodies](../planning/issues/CP.md) are prepared inputs. They contain no verified GitHub issue IDs or Project identity. The [setup procedure](PROJECT_SETUP.md) requires authenticated discovery, reconciliation and readback.", "", "## Program acceptance", "", *bullet_list(backlog["program"]["acceptance_criteria"]), "", "## Implementation phases", "", "Phase names express delivery gates; they are not promises of dates or current production readiness.", ""]
    for phase in releases["phases"]:
        lines.extend([f"### {phase['name']}", "", f"**{len(phase['required_work_packages'])} work packages.** {phase['gate']}", "", "Required package IDs: " + ", ".join(native_link(identifier) for identifier in phase["required_work_packages"]) + ".", ""])
    lines.extend(["## Workstreams and independently reviewable outcomes", ""])
    for epic in backlog["epics"]:
        lines.extend([f"### {epic['id']}: {epic['title']}", "", epic["outcome"], "", f"Native epic body: {native_link(epic['id'])}.", "", "| Package | Outcome | Priority | Release phase |", "| --- | --- | --- | --- |"])
        for package in epic["work_packages"]:
            lines.append(f"| {native_link(package['id'])} — {cell(package['title'])} | {cell(package['outcome'])} | {package['priority']} | {package['phase']} |")
        lines.append("")
    lines.extend(["## Decisions and release impact", "", "Role names identify needed decision authority; the blank actual approver lists do not imply anyone has accepted a new duty. Existing accepted boundaries are cited upstream rather than re-approved locally.", ""])
    for decision in decisions["decisions"]:
        lines.extend([f"### {decision['id']}: {decision['title']}", "", f"**Status:** {decision['status']}. **Decision role:** {decision['responsible_decision_role']}.", "", decision["decision"], "", "Options and tradeoffs:", ""])
        lines.extend(f"- **{option['option']}** — {option['tradeoffs']}" for option in decision["options"])
        lines.extend(["", "Consequences:", "", *bullet_list(decision["consequences"]), "", "Affected release gates: " + ", ".join(decision["affected_release_gate"]) + ".", "", "Packages: " + ", ".join(native_link(identifier) for identifier in decision["work_packages"]) + ".", "", decision["authority_and_limits"]])
        if decision["references"]:
            lines.extend(["", "References:", "", *bullet_list(decision["references"])])
        lines.append("")
    lines.extend(["## Ecosystem coverage", "", coverage["purpose"], "", "Unknown measured counts remain null, not zero. Breadth, depth, freshness, rights and consumer delivery remain separate dimensions. This plan makes no claim of completeness of all AI.", "", "| Domain | Scope and qualification boundary | Implementation packages |", "| --- | --- | --- |"])
    for domain in coverage["domains"]:
        lines.append(f"| {cell(domain['title'])} | {cell(domain['boundary'])} | {', '.join(native_link(identifier) for identifier in domain['work_packages'])} |")
    lines.extend(["", "## Non-goals", "", *bullet_list(backlog["non_goals"]), "", "## Bootstrap versus production", "", releases["bootstrap"]["meaning"], "", "Required bootstrap receipts:", "", *bullet_list(releases["bootstrap"]["required_receipts"]), "", "Forbidden completion inferences:", "", *bullet_list(releases["forbidden_inferences"]), ""])
    return "\n".join(lines)


def render_dependencies(bundle: dict[str, Any], records: list[dict[str, Any]]) -> str:
    packages = [record for record in records if record["level"] == "Work Package"]
    parents = [(record["id"], record["parent"]) for record in records if record.get("parent")]
    edges = [(record["id"], dependency) for record in records for dependency in record.get("blocked_by", [])]
    lines = [GENERATED, "", "# Hierarchy, prerequisites and receiving handoffs", "", f"The intended target-repository hierarchy has **{len(parents)} native parent edges**. The implementation plan has **{len(edges)} native blocked-by edges**. Both are proposed relationships until GitHub readback verifies them; the external research-parent relationship is tracked separately.", "", "Parent/child expresses decomposition. Blocked-by names a prerequisite outcome needed for the dependent package's acceptance. Role vacancies, decision gates and aggregate child progress are explained in the issue bodies; they do not automatically create extra native edges.", "", "## Internal prerequisite map", "", "| Dependent package | Required accepted packages | Result needed from prerequisites |", "| --- | --- | --- |"]
    index = {record["id"]: record for record in records}
    for package in packages:
        deps = package.get("blocked_by", [])
        links = ", ".join(native_link(identifier) for identifier in deps) if deps else "No native prerequisite"
        why = " ".join(f"{identifier}: {index[identifier]['outcome']}" for identifier in deps) if deps else "Ownership, scope and applicable decision gates still require acceptance."
        lines.append(f"| {native_link(package['id'])} — {cell(package['title'])} | {links} | {cell(why)} |")
    lines.extend(["", "## Canonical authority and external receiving handoffs", "", "The following links are informational authority or receiving boundaries. They are **not automatically unresolved native blockers**. The accepted outputs of research #39, #40, #41, #42 and #60 are reused. Do not reopen their completed criteria or create replacement research issues to populate this Project. A new source-use or semantic change needs a concrete new decision under the existing process.", "", "| Canonical reference or handoff | Packages that consume it |", "| --- | --- |"])
    handoffs: dict[str, list[str]] = {}
    for package in packages:
        for url in package.get("external_handoffs", []):
            handoffs.setdefault(url, []).append(package["id"])
    for url in sorted(handoffs):
        lines.append(f"| {url} | {', '.join(native_link(identifier) for identifier in handoffs[url])} |")
    lines.extend(["", "## Consumer receiving boundaries", "", "| Consumer | Canonical contract | Required pipeline packages | State |", "| --- | --- | --- | --- |"])
    for consumer in bundle["coverage"]["consumer_contracts"]:
        lines.append(f"| {consumer['id']} | {consumer['source']} | {', '.join(native_link(identifier) for identifier in consumer['work_packages'])} | {cell(consumer['state'])} |")
    lines.extend(["", "## Reconciliation and completion", "", "1. Resolve stable IDs from the recorded issue marker and actual repository identity; inspect all pages and all states before creating missing issues.", "2. Preserve existing ancestry and live execution values. An unexpected parent is a conflict to investigate, not permission to force reparent.", "3. Verify every prerequisite outcome at its accepted artifact revision. A planned field value or closed unrelated issue is insufficient.", "4. Read back native hierarchy and blocker sets independently, including pagination, and check missing/extra edges and cycles.", "5. Require an actual receiving receipt for each affected consumer. One client's acceptance does not establish another client's compatibility or production activation.", "", "The local [release manifest](../planning/release-manifest.json) separates bootstrap preparation from pilot, consumer, operational and expansion acceptance. The JSON plan is a scope baseline, not a controller that resets live status.", ""])
    return "\n".join(lines)


def render_readme(records: list[dict[str, Any]]) -> str:
    lines = [GENERATED, "", "# Structured planning baseline", "", "The four source JSON files below own versioned scope, decisions, release gates and coverage. GitHub owns live issue state, Assignees, native relationships, discussion and Project values after publication.", "", "| Source | Purpose |", "| --- | --- |", "| [project-backlog.json](project-backlog.json) | Program, epics, independently reviewable packages, tasks/subtasks, prerequisites and acceptance |", "| [decision-register.json](decision-register.json) | Existing boundaries, proposed decisions, options, accountable roles and release impact |", "| [release-manifest.json](release-manifest.json) | Bootstrap evidence boundary and required implementation phase gates |", "| [coverage-matrix.json](coverage-matrix.json) | Capability and domain mappings, unknown measurement counts and consumer contracts |", "", "## Generated projections", "", "| Output | Purpose |", "| --- | --- |", "| [Delivery plan](../docs/DELIVERY_PLAN.md) | Hierarchy, sequencing, decisions and coverage |", "| [Dependencies](../docs/DEPENDENCIES.md) | Native prerequisites separated from informational handoffs |", "| [GitHub issue payloads](github-issue-payloads.json) | Prepared new-issue inputs with symbolic parent/dependency IDs and baseline Project fields |", "| [Issue bodies](issues/CP.md) | Readable bodies for all intended native issues |", "", f"There are {len(records)} prepared native issue bodies. Each uses exactly one stable marker such as `<!-- {MARKER_PREFIX}CP-01.01 -->`. No output contains invented GitHub issue IDs or a guessed Project number.", "", "Payloads are for **new resources only**. Existing issue bodies, assignees, comments, checklist progress, decisions and Project values must remain intact. Resolve live identities and refresh current state before every mutation; do not replay initial Backlog values into existing work.", "", "Task and subtask checklists are contained only in work-package bodies. Program/epic child tables identify native relationship targets without maintaining a duplicate child-completion checklist.", "", "## Regenerate and verify", "", "```bash", "python scripts/render_docs.py", "python scripts/validate_plan.py", "python scripts/render_docs.py --check", "python -m unittest discover -s tests -v", "```", "", "The renderer uses only local source files. It performs no network request, GitHub mutation, source retrieval or deployment. `--check` exits nonzero for missing, modified or unexpected generated outputs and never repairs files. Source-byte SHA-256 values in the payload make every input edit traceable.", "", "Do not treat generated documentation as a second editable source of scope. Review planned changes in JSON, regenerate, inspect the diff and verify. Published or observed state belongs in a separate attributable execution receipt; file presence does not establish remote creation.", ""]
    return "\n".join(lines)


def expected_outputs(root: Path) -> dict[str, str]:
    bundle, digests = load_sources(root)
    records = native_records(bundle["backlog"])
    payload = make_payload(bundle, digests, records)
    outputs = {
        "docs/DELIVERY_PLAN.md": render_delivery(bundle, records),
        "docs/DEPENDENCIES.md": render_dependencies(bundle, records),
        "planning/README.md": render_readme(records),
        "planning/github-issue-payloads.json": json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
    }
    for item in payload["items"]:
        outputs[f"planning/issues/{item['id']}.md"] = item["body"]
    return outputs


def unexpected_issue_files(root: Path, outputs: dict[str, str]) -> list[str]:
    return sorted(
        path.relative_to(root).as_posix()
        for path in (root / "planning/issues").glob("*.md")
        if path.relative_to(root).as_posix() not in outputs
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1], help="Repository root containing the four planning source files")
    parser.add_argument("--check", action="store_true", help="Verify all generated outputs without writing anything")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        outputs = expected_outputs(root)
    except (OSError, UnicodeError, json.JSONDecodeError, KeyError, TypeError, RenderError) as error:
        print(f"Cannot render planning documents: {error}", file=sys.stderr)
        return 1
    extras = unexpected_issue_files(root, outputs)
    if extras:
        for relative in extras:
            print(f"Unexpected generated issue file; reconcile its stable identity before removal: {relative}", file=sys.stderr)
        return 1
    if args.check:
        failures = []
        for relative, content in outputs.items():
            target = root / relative
            if not target.is_file():
                failures.append(f"Missing generated output: {relative}")
            elif target.read_bytes() != content.encode("utf-8"):
                failures.append(f"Generated output drift: {relative}")
        for failure in failures:
            print(failure, file=sys.stderr)
        if failures:
            return 1
        print(f"Generated documents verified: {len(outputs)} outputs; no network or GitHub mutations.")
        return 0
    for relative, content in outputs.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode("utf-8"))
    print(f"Rendered {len(outputs)} outputs, including {sum(path.startswith('planning/issues/') for path in outputs)} prepared issue bodies; no GitHub resources created.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
